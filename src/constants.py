BEAT2ID: dict[float, int] = {
    1.0: 0, 2.0: 1, 3.0: 2, 4.0: 3,
}
"""拍位 → 量化 ID (5 类，含 'other'=4)"""

ID2BEAT: dict[int, float] = {v: k for k, v in BEAT2ID.items()}
ID2BEAT[4] = 0.0  # 'other' 映射到 0


def quantize_duration(dur_beats: float) -> int:
    """将连续时值映射到最近的量化 bin。"""
    if dur_beats <= 0:
        return 3  # 默认四分音符
    # 找到最近的 bin
    bins = sorted(DUR2ID.keys())
    best = bins[0]
    for b in bins:
        if abs(dur_beats - b) < abs(dur_beats - best):
            best = b
    return DUR2ID.get(best, 3)


def quantize_beat(beat: float) -> int:
    """将拍位映射到量化 bin。"""
    # 量化到最近的整数拍
    rounded = round(beat)
    if 1 <= rounded <= 4:
        return BEAT2ID.get(float(rounded), 4)
    return 4  # 'other'


